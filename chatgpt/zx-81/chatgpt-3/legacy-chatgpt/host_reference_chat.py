#!/usr/bin/env python3
"""PC reference for PIOCO's current 2304-byte dictionary/trigram format.

Run from repository root:
  python CHATGPT/host_reference_chat.py --self-test
  python CHATGPT/host_reference_chat.py
  python CHATGPT/host_reference_chat.py --prompt "WHO MADE YOU ?" --temperature 1

This is a PC reference, NOT the ZX81 runtime and NOT a modern LLM.
It reads kazetta/adat/szotar.bin generated by eszkozok/tokengen.py.
Only the Python standard library is used.
"""
from __future__ import annotations

import argparse
import random
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DICT = ROOT / "kazetta" / "adat" / "szotar.bin"

RECORD_AREA = 1144
LETTER_AREA = 16
TRIGRAM_AREA = 1000
TRIGRAM_START = RECORD_AREA + LETTER_AREA
EXPECTED_SIZE = RECORD_AREA + LETTER_AREA + TRIGRAM_AREA + 144
BOUNDARY = 0x01
SUFFIXES = ("-ING", "-ED", "-S", "-LY")
PUNCTUATION = {".", ",", "?", "!", ";"}


def normalize(value: str) -> str:
    value = value.upper()
    for old, new in (
        ("DOESN'T", "DOES NOT"),
        ("DON'T", "DO NOT"),
        ("CAN'T", "CAN NOT"),
        ("I'M", "I AM"),
    ):
        value = value.replace(old, new)
    for mark in (".", ",", "?", "!", ";"):
        value = value.replace(mark, " " + mark + " ")
    return " ".join(value.split())


def one_edit_apart(a: str, b: str) -> bool:
    if a == b or abs(len(a) - len(b)) > 1:
        return False
    i = j = edits = 0
    while i < len(a) and j < len(b):
        if a[i] == b[j]:
            i += 1
            j += 1
            continue
        edits += 1
        if edits > 1:
            return False
        if len(a) > len(b):
            i += 1
        elif len(b) > len(a):
            j += 1
        else:
            i += 1
            j += 1
    if i < len(a) or j < len(b):
        edits += 1
    return edits == 1


class TrigramModel:
    def __init__(self, path: Path = DICT, seed: int = 81):
        raw = path.read_bytes()
        if len(raw) != EXPECTED_SIZE:
            raise ValueError(
                "Dictionary is %d bytes; expected %d. Rebuild with "
                "python eszkozok/tokengen.py" % (len(raw), EXPECTED_SIZE)
            )

        self.word_to_id: dict[str, int] = {}
        self.id_to_word: dict[int, str] = {}
        pos = 0
        token_id = 0x20
        while pos < RECORD_AREA and raw[pos]:
            size = raw[pos]
            end = pos + 1 + size
            if end > RECORD_AREA:
                raise ValueError("Token record crosses the dictionary record area")
            word = raw[pos + 1:end].decode("ascii")
            self.word_to_id[word] = token_id
            self.id_to_word[token_id] = word
            token_id += 1
            pos = end

        if token_id != 0xF0:
            raise ValueError("Expected continuous word IDs 0x20..0xEF; got %d" %
                             (token_id - 0x20))

        self.letters = raw[RECORD_AREA:TRIGRAM_START].decode("ascii")
        if len(self.letters) != LETTER_AREA or len(set(self.letters)) != LETTER_AREA:
            raise ValueError("The 16-letter fallback table is invalid")
        self.letter_to_id = {
            char: 0xF0 + index for index, char in enumerate(self.letters)
        }

        self.trigrams: list[tuple[int, int, int, int]] = []
        end = TRIGRAM_START + TRIGRAM_AREA
        for offset in range(TRIGRAM_START, end, 4):
            a, b, c, weight = raw[offset:offset + 4]
            if a == b == c == weight == 0:
                continue
            self.trigrams.append((a, b, c, weight & 0x0F))
        if not self.trigrams:
            raise ValueError("No trigram records found")
        self.rng = random.Random(seed)

    def tokenize(self, text: str, correct_typos: bool = True) -> list[int]:
        result: list[int] = []
        for word in normalize(text).split():
            if word in self.word_to_id:
                result.append(self.word_to_id[word])
                continue

            decomposed = False
            for suffix in SUFFIXES:
                ending = suffix[1:]
                stem = word[:-len(ending)] if word.endswith(ending) else ""
                if (stem in self.word_to_id and suffix in self.word_to_id
                        and len(stem) >= 2):
                    result.extend((self.word_to_id[stem],
                                   self.word_to_id[suffix]))
                    decomposed = True
                    break
            if decomposed:
                continue

            # Conservative typo correction: only one unique candidate.
            if correct_typos and len(word) >= 4:
                close = [candidate for candidate in self.word_to_id
                         if len(candidate) >= 4 and one_edit_apart(word, candidate)]
                if len(close) == 1:
                    result.append(self.word_to_id[close[0]])
                    continue

            # Unknown words become a bounded sequence of known letter tokens.
            result.append(BOUNDARY)
            result.extend(self.letter_to_id[ch] for ch in word
                          if ch in self.letter_to_id)
            result.append(BOUNDARY)
        return result

    def candidates(self, context: tuple[int, int]) -> list[tuple[int, int]]:
        first, second = context
        scores: dict[int, int] = {}
        for a, b, following, weight in self.trigrams:
            if a == first and b == second:
                scores[following] = scores.get(following, 0) + weight + 1

        # One-token backoff if no exact two-token context exists.
        if not scores:
            for _a, b, following, weight in self.trigrams:
                if b == second:
                    scores[following] = scores.get(following, 0) + weight + 1
        return sorted(scores.items(), key=lambda item: (item[1], item[0]),
                      reverse=True)

    def choose(self, candidates: list[tuple[int, int]], temperature: int) -> int:
        if not candidates:
            raise ValueError("No continuation candidates")
        if temperature == 1:
            return candidates[0][0]
        pool_size = {2: 2, 3: 4, 4: 8}[temperature]
        pool = candidates[:pool_size]
        return self.rng.choices(
            [token for token, _score in pool],
            weights=[score for _token, score in pool],
            k=1,
        )[0]

    def decode(self, tokens: list[int]) -> str:
        words: list[str] = []
        letters = ""
        for token in tokens:
            if token == BOUNDARY:
                if letters:
                    words.append(letters)
                    letters = ""
                continue
            if token >= 0xF0:
                letters += self.letters[token - 0xF0]
                continue
            if letters:
                words.append(letters)
                letters = ""
            word = self.id_to_word.get(token)
            if not word:
                continue
            if word.startswith("-") and words:
                words[-1] += word[1:]
            elif word in PUNCTUATION and words:
                words[-1] += word
            else:
                words.append(word)
        if letters:
            words.append(letters)
        return " ".join(words)

    def generate(self, prompt: str, temperature: int = 2,
                 max_tokens: int = 24) -> tuple[str, int, int]:
        if temperature not in (1, 2, 3, 4):
            raise ValueError("Temperature must be 1..4")
        prompt_tokens = self.tokenize(prompt)
        if len(prompt_tokens) < 2:
            return "", len(prompt_tokens), 0
        context = (prompt_tokens[-2], prompt_tokens[-1])
        generated: list[int] = []
        for _ in range(max_tokens):
            choices = self.candidates(context)
            if not choices:
                break
            next_token = self.choose(choices, temperature)
            generated.append(next_token)
            context = (context[1], next_token)
            if len(generated) >= 4:
                if self.id_to_word.get(next_token) in {".", "?", "!"}:
                    break
        return self.decode(generated), len(prompt_tokens), len(generated)


def self_test(model: TrigramModel) -> None:
    prompts = ("WHAT IS YOUR NAME ?", "WHO MADE YOU ?",
               "WHO IS SAFAR SANDOR ?")
    failures = []
    for prompt in prompts:
        answer, incoming, outgoing = model.generate(prompt, temperature=1)
        print("%s -> %s" % (prompt, answer or "[NO CONTINUATION]"))
        if not answer or not outgoing:
            failures.append(prompt)
    if failures:
        raise SystemExit("No continuation for: " + " | ".join(failures))
    print("OK: %d basic generation prompts produced output." % len(prompts))


def main() -> None:
    parser = argparse.ArgumentParser(description="PIOCO host-side trigram reference")
    parser.add_argument("--prompt")
    parser.add_argument("--temperature", type=int, choices=(1, 2, 3, 4), default=2)
    parser.add_argument("--max-tokens", type=int, default=24)
    parser.add_argument("--seed", type=int, default=81)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()

    try:
        model = TrigramModel(seed=args.seed)
    except (OSError, ValueError) as exc:
        raise SystemExit("Cannot load dictionary: %s" % exc)

    if args.self_test:
        self_test(model)
        return

    if args.prompt is not None:
        start = time.perf_counter()
        answer, incoming, outgoing = model.generate(
            args.prompt, args.temperature, args.max_tokens)
        elapsed = (time.perf_counter() - start) * 1000
        print("YOU   [%d tokens] %s" % (incoming, args.prompt))
        print("PIOCO [%d tokens | %.1f ms] %s" %
              (outgoing, elapsed, answer or "[NO LEARNED CONTINUATION]"))
        return

    temperature = args.temperature
    print("PIOCO AI — host reference (not the ZX81 runtime)")
    print("Commands: /temp 1..4, /help, /quit")
    while True:
        try:
            prompt = input("YOU> ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            break
        if not prompt:
            continue
        if prompt.lower() in ("/quit", "/exit"):
            break
        if prompt.lower() == "/help":
            print("Enter an English prompt. /temp 1..4 changes sampling diversity.")
            continue
        if prompt.lower().startswith("/temp "):
            try:
                value = int(prompt.split(maxsplit=1)[1])
                if value not in (1, 2, 3, 4):
                    raise ValueError
                temperature = value
                print("Temperature = %d" % temperature)
            except ValueError:
                print("Use /temp 1, /temp 2, /temp 3 or /temp 4.")
            continue

        start = time.perf_counter()
        answer, incoming, outgoing = model.generate(prompt, temperature)
        elapsed = (time.perf_counter() - start) * 1000
        print("YOU   [%d tokens] %s" % (incoming, prompt))
        print("PIOCO [%d tokens | %.1f ms] %s" %
              (outgoing, elapsed, answer or "[NO LEARNED CONTINUATION]"))


if __name__ == "__main__":
    main()
