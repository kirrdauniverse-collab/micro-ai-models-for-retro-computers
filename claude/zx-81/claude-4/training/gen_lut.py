#!/usr/bin/env python3
"""Generate engine/rt_lut.h - the exp lookup table shared by the C engine
and the numpy integer simulator (training/intsim.py).

RT_EXP_LUT[k] = round(exp(-k / 8.0) * 4096)   (Q12 weights, k = 0..255)

Sampling uses k = (max_logit - logit) >> (3 + temp_sh), so the table covers
a logit gap of up to 255*8 = 2040 units, plenty for our logit ranges.
Run from the repo root:  python3 training/gen_lut.py
"""
import math
import os

HEADER = """/* rt_lut.h - GENERATED by training/gen_lut.py, do not edit by hand.
 * RT_EXP_LUT[k] = round(exp(-k/8.0) * 4096), Q12 softmax weights.
 * The same table exists in training/intsim.py; keep them in sync by
 * re-running the generator.
 */
#ifndef RT_LUT_H
#define RT_LUT_H

#include "rt_types.h"

static const rt_u16 RT_EXP_LUT[256] = {
%s
};

#endif /* RT_LUT_H */
"""


def main():
    vals = [int(round(math.exp(-k / 8.0) * 4096.0)) for k in range(256)]
    assert vals[0] == 4096
    rows = []
    for r in range(0, 256, 8):
        rows.append("    " + ", ".join("%5d" % v for v in vals[r:r + 8]) + ",")
    body = "\n".join(rows)
    out = os.path.join(os.path.dirname(__file__), "..", "engine", "rt_lut.h")
    with open(os.path.abspath(out), "w") as f:
        f.write(HEADER % body)
    print("engine/rt_lut.h written, first/last:", vals[0], vals[255])


if __name__ == "__main__":
    main()
